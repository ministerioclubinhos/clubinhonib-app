import { chromium } from '@playwright/test';
const [,, out, url, w, h, testid] = process.argv;
const browser = await chromium.launch();
const ctx = await browser.newContext({ storageState: 'e2e/.auth/admin.json', viewport: { width: +w, height: +h }, locale: 'pt-BR' });
const page = await ctx.newPage();
await page.goto(url, { waitUntil: 'networkidle' });
await page.getByTestId(testid).waitFor({ timeout: 45000 }).catch(() => {});
await page.waitForTimeout(2500);
await page.screenshot({ path: out, fullPage: true });
await browser.close();
